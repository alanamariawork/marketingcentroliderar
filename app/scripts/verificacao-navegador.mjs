await dlg.getByLabel('Link do Canva').fill('canva sem https')
await page.getByRole('button', { name: 'Salvar' }).click()
ok('link inválido bloqueado', (await dlg.getByText(/comece com https/).count()) >= 1)
await dlg.getByLabel('Link do Canva').fill('https://www.canva.com/design/abc')
await dlg.getByLabel('Anexo de vídeo local').setInputFiles({ name: 'clipe.mp4', mimeType: 'video/mp4', buffer: Buffer.from('00000000') })
