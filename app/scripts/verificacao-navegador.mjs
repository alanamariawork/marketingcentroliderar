import { chromium } from 'playwright'
import { writeFileSync, mkdirSync } from 'node:fs'

// Verificação ponta a ponta no navegador (Playwright).
// Uso: npm run build && npx vite preview --port 4173, e em outro terminal:
//   npm i --no-save playwright && node scripts/verificacao-navegador.mjs
// CHROMIUM_PATH aponta para um Chromium já instalado, se necessário.
const BASE = process.env.BASE_URL ?? 'http://localhost:4173/'
const OUT = new URL('../verificacao/', import.meta.url).pathname
mkdirSync(OUT, { recursive: true })
const results = []
process.on('exit', () => console.log(results.join('\n')))
const ok = (name, cond, extra = '') => { results.push(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`) }

