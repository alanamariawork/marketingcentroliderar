import { chromium } from 'playwright'
import { writeFileSync, mkdirSync } from 'node:fs'

// Verificação ponta a ponta no navegador (Playwright).
// Uso: npm run build && npx vite preview --port 4173, e em outro terminal:
//   npm i --no-save playwright && node scripts/verificacao-navegador.mjs
// CHROMIUM_PATH aponta para um Chromium já instalado, se necessário.
const BASE = process.env.BASE_URL ?? 'http://localhost:4173/'
const OUT = new URL('../verificacao/', import.meta.url).pathname
mkdirSync(OUT, { recursive: true })
const results = []
process.on('exit', () => console.log(results.join('\n')))
const ok = (name, cond, extra = '') => { results.push(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`) }

const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {})
const ctx = await browser.newContext({ viewport: { width: 1366, height: 900 }, locale: 'pt-BR', timezoneId: 'America/Fortaleza' })
await ctx.route(/drive\.google\.com|instagram|canva/, (r) => r.abort())
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && !/ERR_FAILED|net::/.test(m.text()) && errors.push(m.text()))

const go = async (emp, pag) => { await page.goto(`${BASE}#/${emp}/${pag}`); await page.waitForTimeout(400) }

// 1. Navegação
for (const emp of ['smart-games', 'up-machines', 'centro-liderar']) {
  for (const pag of ['cronograma', 'atividades', 'insights', 'drive', 'dashboard']) {
    await go(emp, pag)
    const h1 = await page.locator('h1').innerText()
    ok(`navegação ${emp}/${pag}`, h1.toLowerCase() === pag, h1)
  }
}
ok('sem faixa "Produção → Decisão final"', !(await page.content()).includes('Decisão final →'))
ok('sem "Claude IA"', !(await page.content()).includes('Claude IA'))

// 2. Sidebar: empresa e página em destaque
await go('centro-liderar', 'atividades')
ok('página atual com aria-current', (await page.locator('aside a[aria-current="page"]').innerText()).includes('Atividades'))

// 3. Atividades demonstrativas e aprovação
ok('3 atividades demo no Centro Liderar', (await page.getByText('3 entregas').count()) === 1)
await go('smart-games', 'atividades')
ok('Smart Games sem atividades (isolamento)', (await page.getByText('Nenhuma atividade cadastrada').count()) === 1)

// Criar atividade na Smart Games com material e vídeo
await page.getByRole('button', { name: 'Adicionar atividade' }).first().click()
const dlg = page.getByRole('dialog')
await dlg.getByLabel('Título').fill('Teste lançamento')
await dlg.getByLabel('Formato de postagem').selectOption('Live')
const formatos = await dlg.getByLabel('Formato de postagem').locator('option').allInnerTexts()
ok('7 formatos', formatos.length === 8, formatos.join(','))
const resp = await dlg.getByLabel('Responsável').locator('option').allInnerTexts()
ok('responsáveis sem Anny', !resp.includes('Anny') && resp.includes('Jordana'), resp.join(','))
await dlg.getByLabel('Hora da postagem').fill('10:30')
await page.getByRole('button', { name: 'Salvar' }).click()
ok('hora sem data bloqueada', (await dlg.getByText('Informe a data da postagem para definir o horário.').count()) === 1)
ok('campos preservados após erro', (await dlg.getByLabel('Título').inputValue()) === 'Teste lançamento')
await dlg.getByLabel('Data da postagem').fill('2026-10-23')
await dlg.getByLabel('Link do Canva').fill('canva sem https')
await page.getByRole('button', { name: 'Salvar' }).click()
ok('link inválido bloqueado', (await dlg.getByText(/comece com https/).count()) >= 1)
await dlg.getByLabel('Link do Canva').fill('https://www.canva.com/design/abc')
await dlg.getByLabel('Anexo de vídeo local').setInputFiles({ name: 'clipe.mp4', mimeType: 'video/mp4', buffer: Buffer.from('00000000') })
ok('prévia de vídeo no formulário', (await dlg.locator('video').count()) === 1)
await dlg.getByRole('button', { name: 'Remover vídeo' }).click()
ok('remover vídeo antes de salvar', (await dlg.locator('video').count()) === 0)
await dlg.getByLabel('Anexo de vídeo local').setInputFiles({ name: 'clipe.mp4', mimeType: 'video/mp4', buffer: Buffer.from('00000000') })
await page.getByRole('button', { name: 'Salvar' }).click()
await page.waitForTimeout(300)
ok('atividade criada', (await page.locator('h3', { hasText: 'Teste lançamento' }).count()) === 1)
await page.screenshot({ path: OUT + 'atividades-smart.png', fullPage: true })
await go('up-machines', 'atividades')
ok('atividade não aparece em Up Machines', (await page.getByText('Teste lançamento').count()) === 0)

// Cronograma: vínculo com a data
await go('smart-games', 'cronograma')
await page.getByLabel('Ir para a data').fill('2026-10-23')
await page.waitForTimeout(200)
ok('atividade no cronograma mensal', (await page.getByRole('button', { name: /10:30.*Teste lançamento/ }).count()) === 1)
await page.getByRole('button', { name: 'Semanal' }).click()
const boxes = await page.locator('section[aria-label*="postagens"]').evaluateAll((els) => els.map((e) => e.getBoundingClientRect().top))
ok('semana: 7 dias lado a lado', boxes.length === 7 && new Set(boxes.map(Math.round)).size === 1, String(boxes.length))
await page.screenshot({ path: OUT + 'cronograma-semanal.png', fullPage: true })
for (const [vis, n] of [['Semestral', 6], ['Anual', 12], ['Trimestral', 3]]) {
  await page.getByRole('button', { name: vis, exact: true }).click()
  const tops = await page.locator('section[aria-label$=" de 2026"], section[aria-label$=" de 2027"]').evaluateAll((els) => els.map((e) => Math.round(e.getBoundingClientRect().top)))
  const rows = new Set(tops).size
  ok(`${vis}: ${n} meses em ${n / 3} fileira(s) de 3`, tops.length === n && rows === n / 3, `${tops.length} meses, ${rows} fileiras`)
  if (vis !== 'Trimestral') await page.screenshot({ path: OUT + `cronograma-${vis.toLowerCase()}.png`, fullPage: true })
}
await page.getByRole('button', { name: 'Diária' }).click()
ok('visualização diária', (await page.locator('section[aria-label*="postagens"]').count()) === 1)
await page.getByRole('button', { name: 'Hoje' }).click()
ok('botão Hoje destaca o dia', (await page.getByText('Hoje', { exact: true }).count()) >= 1)
await page.getByRole('button', { name: 'Mensal' }).click()
await page.getByLabel('Ir para a data').fill('2026-10-23')
await page.getByRole('button', { name: /10:30.*Teste lançamento/ }).click()
ok('abre detalhes pelo cronograma', (await page.getByRole('dialog').getByText('Material para aprovação').count()) >= 1)
ok('vídeo reproduzível no detalhe', (await page.getByRole('dialog').locator('video').count()) === 1)
// Carlos envia; Kélvia aprova
ok('Carlos não vê "Aprovar versão"', (await page.getByRole('button', { name: 'Aprovar versão' }).count()) === 0)
await page.getByRole('button', { name: 'Enviar para aprovação' }).click()
await page.keyboard.press('Escape')
await page.getByLabel('Simular perfil').selectOption('Kélvia')
await go('smart-games', 'atividades')
await page.getByRole('button', { name: 'Aguardando Kélvia' }).click()
ok('filtro Aguardando Kélvia', (await page.locator('h3', { hasText: 'Teste lançamento' }).count()) === 1 && (await page.locator('article').count()) === 1)
await page.getByRole('button', { name: /Revisar entrega/ }).click()
await page.getByRole('button', { name: 'Solicitar ajustes' }).click()
ok('ajuste exige orientação', (await page.getByText('Descreva os ajustes antes de enviar.').count()) === 1)
await page.getByLabel('Orientação para ajustes').fill('Trocar a trilha')
await page.getByRole('button', { name: 'Solicitar ajustes' }).click()
ok('histórico registra ajustes', (await page.getByRole('dialog').getByText(/solicitou ajustes na versão 1: Trocar a trilha/).count()) === 1)
await page.keyboard.press('Escape')
await page.getByLabel('Simular perfil').selectOption('Carlos')
await page.getByRole('button', { name: 'Aguardando Kélvia' }).click()
ok('ajustes voltam para Em produção sinalizados', (await page.locator('section[aria-labelledby="coluna-Em produção"]').getByText('Ajustes solicitados').count()) === 1)
await page.getByRole('button', { name: /Abrir entrega.*Teste/ }).click()
await page.getByRole('button', { name: 'Enviar para aprovação' }).click()
await page.keyboard.press('Escape')
await page.getByLabel('Simular perfil').selectOption('Kélvia')
await page.getByRole('button', { name: /Revisar entrega/ }).click()
await page.getByRole('button', { name: 'Aprovar versão' }).click()
ok('Kélvia aprova versão 2', (await page.getByRole('dialog').getByText('Kélvia aprovou a versão 2.').count()) === 1)
await page.keyboard.press('Escape')
await page.getByLabel('Simular perfil').selectOption('Carlos')

// Insights
await go('centro-liderar', 'insights')
await page.waitForSelector('text=Resultados por publicação')
ok('pasta da Jaciara: 1.124 registros', (await page.getByRole('button', { name: /Jaciara Mendes — Instagram\s*1\.124 registros/ }).count()) === 1)
ok('Centro Liderar 50', (await page.getByRole('button', { name: /Centro Liderar — Instagram\s*50 registros/ }).count()) === 1)
ok('MQA 29', (await page.getByRole('button', { name: /MQA — Instagram\s*29 registros/ }).count()) === 1)
ok('contas novas sem dados', (await page.getByRole('button', { name: /Jaciara — TikTok\s*0 registros/ }).count()) === 1)
await page.getByLabel('Funil').selectOption('NUTRIÇÃO')
const nutr = await page.getByText(/publicações neste filtro/).innerText()
ok('filtro NUTRIÇÃO inclui NUTRICAO da Jaciara', /^2/.test(nutr) || parseInt(nutr.replace('.', '')) > 200, nutr)
await page.screenshot({ path: OUT + 'insights.png' })
await page.getByRole('button', { name: /MQA — Instagram/ }).click()
await go('centro-liderar', 'dashboard')
const antes = await page.locator('.card', { hasText: 'Publicações registradas' }).locator('p').nth(1).innerText()
await go('centro-liderar', 'insights')
await page.getByRole('button', { name: 'Adicionar dados' }).click()
const f = page.getByRole('dialog')
ok('regra MQA sugerida para a conta MQA', (await f.getByLabel('Regra de score').inputValue()) === 'mqa')
await f.getByLabel('Funil').selectOption('ESCALA')
await f.getByLabel('Formato').selectOption('Reels')
await f.getByLabel('Descrição').fill('Post teste e2e')
await f.getByLabel('Link do post').fill('https://www.instagram.com/p/DdHcK62EcFo/?x=1')
await f.getByLabel('Reproduções').fill('100')
await page.getByRole('button', { name: 'Salvar resultados' }).click()
ok('duplicação na mesma conta bloqueada', (await f.getByText(/já está cadastrado nesta conta/).count()) === 1)
ok('exige data de coleta', (await f.getByText('Informe a data de coleta das métricas.').count()) === 1)
await f.getByLabel('Link do post').fill('https://www.instagram.com/p/NOVOPOSTE2E/')
await f.getByLabel('Data da publicação').fill('2026-10-15')
await f.getByLabel('Data da coleta').fill('2026-10-20')
await f.getByLabel('Compartilhamentos').fill('0')
await f.getByLabel('Seguimentos / novos seguidores').fill('6')
ok('score MQA ao vivo', (await f.getByText('Score recalculado: 106').count()) === 1)
await page.getByRole('button', { name: 'Salvar resultados' }).click()
await page.waitForTimeout(400)
ok('sucesso após gravar', (await page.getByText('Resultados salvos. O Dashboard foi atualizado automaticamente.').count()) === 1)
await go('centro-liderar', 'dashboard')
const depois = await page.locator('.card', { hasText: 'Publicações registradas' }).locator('p').nth(1).innerText()
ok('Dashboard atualizado após salvar', Number(depois) === Number(antes) + 1, `${antes} → ${depois}`)
ok('ranking MQA presente', (await page.getByText(/MQA · reproduções/).count()) === 1)
ok('observação: distribuição editorial', (await page.getByText('distribuição editorial').count()) >= 1)
await page.screenshot({ path: OUT + 'dashboard-mqa.png', fullPage: true })
await page.reload(); await page.waitForTimeout(800)
await go('centro-liderar', 'insights')
await page.getByRole('button', { name: /MQA — Instagram/ }).click()
ok('persistência após recarregar', (await page.locator('tbody p', { hasText: 'Post teste e2e' }).count()) === 1)
const ls = await page.evaluate(() => JSON.parse(localStorage.getItem('mendes-insights-v1')).length)
ok('localStorage mendes-insights-v1 com 1.204 registros', ls === 1204, String(ls))
ok('catálogo do Drive fora do localStorage', await page.evaluate(() => JSON.stringify(localStorage).length < 3_000_000))
// atividades de sessão somem ao recarregar
await go('smart-games', 'atividades')
ok('atividades são da sessão (somem ao recarregar)', (await page.getByText('Teste lançamento').count()) === 0)
// Falha de gravação
await page.evaluate(() => localStorage.setItem('gm-marketing:simular-erro', '1'))
await go('centro-liderar', 'insights')
await page.getByRole('button', { name: /MQA — Instagram/ }).click()
await page.waitForTimeout(500)
await page.locator('tbody tr').filter({ hasText: 'Post teste e2e' }).locator('button').click()
await page.getByRole('dialog').getByLabel('Curtidas').fill('5')
await page.getByRole('button', { name: 'Salvar resultados' }).click()
await page.waitForTimeout(300)
ok('falha de gravação mostra erro e mantém campos', (await page.getByRole('dialog').getByText(/Não foi possível salvar/).count()) === 1 && (await page.getByRole('dialog').getByLabel('Curtidas').inputValue()) === '5')
ok('sem toast de sucesso na falha', (await page.getByText('Resultados salvos.').count()) === 0)
await page.evaluate(() => localStorage.removeItem('gm-marketing:simular-erro'))
await page.keyboard.press('Escape')

// Drive
await go('centro-liderar', 'drive')
