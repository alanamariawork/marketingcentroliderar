ok('coluna Aguardando aprovação preservada', (await page.locator('#coluna-Aguardando\\ aprovação').count()) === 1)
await page.getByRole('button', { name: /Abrir entrega.*Bastidores/ }).click()
ok('histórico preservado', (await page.getByRole('dialog').getByText('Kélvia aprovou a versão 1.').count()) === 1)
await page.keyboard.press('Escape')
await page.screenshot({ path: OUT + 'atividades.png', fullPage: true })

